def load_issues(root):
    issues = yaml.safe_load((root / "issues.yml").read_text(encoding="utf-8"))
    if not isinstance(issues, list) or not issues:
        raise ValueError("issues.yml must contain a nonempty list")
    urls = set()
    folders = set()
    for issue in issues:
        if not isinstance(issue, dict) or set(issue) - {"title", "url", "year", "topics", "code"}:
            raise ValueError("Each issue must use only title, url, year, topics, and optional code")
        for field in ("title", "url"):
            if not isinstance(issue.get(field), str) or not issue[field].strip():
                raise ValueError(f"Missing or invalid {field}: {issue}")
        url = urlparse(issue["url"])
        if url.scheme != "https" or url.netloc != "newsletter.francofernando.com" or not url.path.startswith("/p/"):
            raise ValueError(f"Invalid issue URL: {issue['url']}")
        if issue["url"] in urls:
            raise ValueError(f"Duplicate issue URL: {issue['url']}")
        urls.add(issue["url"])
        if type(issue.get("year")) is not int or issue["year"] < 2022:
            raise ValueError(f"Invalid year: {issue}")
        topics = issue.get("topics")
        if not isinstance(topics, list) or not topics or any(topic not in TOPICS for topic in topics):
            raise ValueError(f"Invalid topics: {issue}")
        if len(set(topics)) != len(topics) or ("More" in topics and len(topics) != 1):
            raise ValueError(f"Duplicate or mixed More topics: {issue}")
        if "code" in issue:
            folder = issue["code"]
            if not isinstance(folder, str) or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", folder):
                raise ValueError(f"Invalid code folder: {folder}")
            path = root / "code" / folder
            if not path.is_dir() or path.resolve().parent != (root / "code").resolve():
                raise ValueError(f"Missing or unsafe code folder: {folder}")
            if folder in folders:
                raise ValueError(f"Code folder linked more than once: {folder}")
            folders.add(folder)
    return issues


def start_here(text):
    if START_BEGIN not in text and START_END not in text:
        return f"{START_BEGIN}\n<!-- Add your selected issue links here. -->\n{START_END}"
    if text.count(START_BEGIN) != 1 or text.count(START_END) != 1:
        raise ValueError("Expected exactly one pair of Start here markers")
    begin = text.index(START_BEGIN)
    end = text.index(START_END)
    if end < begin:
        raise ValueError("Start here markers are reversed")
    return text[begin:end + len(START_END)]


def markdown_label(text):
    return text.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]").replace("\n", " ")


def render_index(issues, preserved):
    lines = [
        "# The Polymathic Engineer", "",
        "A newsletter by Franco Fernando about system design, distributed systems, algorithms, and software engineering.",
        f"Published issues and companion code. [Subscribe to the newsletter]({NEWSLETTER}/subscribe).",
        "", "## Start Here", "", preserved, "", "## Issues", "",
    ]
    for topic in TOPICS:
        selected = [issue for issue in issues if topic in issue["topics"]]
        if not selected:
            continue
        lines.extend([f"### {topic}", ""])
        for issue in selected:
            line = f"- [{markdown_label(issue['title'])}]({issue['url']})"
            if "code" in issue:
                line += f" ([code](code/{issue['code']}/))"
            lines.append(line)
        lines.append("")
    lines.extend([
        "## Regenerate", "",
        "Edit `issues.yml` to add or update an issue. Keep entries newest first within each year; list all applicable topics.",
        "The optional `code` value is a folder name under `code/`. Keep these folder names stable after publication.",
        "", "```sh", "python -m pip install -r requirements.txt", "python scripts/generate.py",
        "python -m unittest discover -s scripts -p \"test_*.py\"", "```", "",
        "The generator preserves the marked Start Here block and hand-written code READMEs.",
        "Run commands in a code folder unless its README says otherwise. Existing samples with separate instructions include `RUNNING.md` or `commands.md`.",
        "",
    ])
    return "\n".join(lines)


def code_readme(folder, issue):
    summary, dependencies, commands = EXAMPLES[folder]
    title = issue["title"] if issue else folder
    lines = [GENERATED, "", f"# {title}", "", summary, ""]
    if issue:
        lines.extend([f"[Read the issue]({issue['url']}).", ""])
    lines.extend([
        f"[The Polymathic Engineer]({NEWSLETTER}) | [Subscribe]({NEWSLETTER}/subscribe)",
        "", "## Run", "", dependencies, "", "From this folder:", "",
        "```sh", commands, "```", "",
    ])
    if folder == "interpolation":
        lines.extend(["`trilinear-interpolation.py` defines functions and has no terminal output.", ""])
    return "\n".join(lines)


def generate(root=ROOT):
    root = Path(root)
    issues = load_issues(root)
    readme = root / "README.md"
    preserved = start_here(readme.read_text(encoding="utf-8") if readme.exists() else "")
    outputs = {readme: render_index(issues, preserved)}
    linked = {issue["code"]: issue for issue in issues if "code" in issue}
    code = root / "code"
    for folder in sorted(code.iterdir()) if code.exists() else []:
        if not folder.is_dir():
            continue
        path = folder / "README.md"
        issue = linked.get(folder.name)
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        if existing and not existing.startswith(GENERATED):
            if issue and issue["url"] not in existing:
                outputs[path] = existing + ("" if existing.endswith("\n\n") else "\n\n") + f"[Read the newsletter issue: {issue['title']}]({issue['url']}).\n"
        else:
            if folder.name not in EXAMPLES:
                raise ValueError(f"Add run instructions to EXAMPLES for {folder.name}")
            outputs[path] = code_readme(folder.name, issue)
    for path, content in outputs.items():
        if not path.exists() or path.read_bytes() != content.encode("utf-8"):
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    generate()